#define ANCP_INSTANCE_LEN								(3)
#define ANCP_TRANSACTION_ID_LEN								(3)

struct ancp_transaction_id {
	unsigned char			id[ANCP_TRANSACTION_ID_LEN];
};

struct ancp_cap_field {
	__net16 			cap_type;
	__net16 			cap_length;
	unsigned char	 		cap_data[];
};

struct ancp_tlv {
	__net16				type;
	__net16				length;
	unsigned char			value[];
};

struct ancp_msg_hdr {
	__u8 				version;
	__u8 				message_type;
	__net16					result:4,
						result_code:12;
	__u8				partition_id;
	struct ancp_transaction_id	transaction_id;
	__net16					i_bit:1,
						submsg_num:15;
	__net16				length;
	
};

struct ancp_adj_msg {
	__u8 				version;
	__u8 				message_type;
	__u8 				timer;
	__u8 					m_bit:1,
						code:7;
	unsigned char			sender_name[ETH_ADDR_LEN];
	unsigned char			receiver_name[ETH_ADDR_LEN];
	__net32				sender_port;
	__net32				receiver_port;
	__u8					p_type:4,
						p_flag:4;
	unsigned char			sender_instance[ANCP_INSTANCE_LEN];
	__u8				partition_id;
	unsigned char			receiver_instance[ANCP_INSTANCE_LEN];
	__u8				reserved;
	__u8				num_caps;
	__net16				total_length;
	struct ancp_cap_field		cap_fields[];
};

struct ancp_adj_update_msg {
	__u8 				version;
	__u8 				message_type;
	__net16					result:4,
						code:12;
	__u8				partition_id;
	struct ancp_transaction_id	transaction_id;
	__net16					i_bit:1,
						submsg_num:15;
	__net16				length;
};

