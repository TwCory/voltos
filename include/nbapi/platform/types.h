#ifndef _NBAPI_PLATFORM_TYPES_H_
#define _NBAPI_PLATFORM_TYPES_H_

#include <nbapi/platform/bits.h>
#include <nbapi/platform/bool.h>
#include <nbapi/platform/float64.h>
#include <nbapi/platform/int64.h>

typedef signed char             __s_char;
typedef unsigned char           __u_char;

typedef signed short            __s_short;
typedef unsigned short          __u_short;

typedef signed int              __s_int;
typedef unsigned int            __u_int;

typedef signed long             __s_long;
typedef unsigned long           __u_long;

typedef signed long long        __s_llong;
typedef unsigned long long      __u_llong;

#endif /* _NBAPI_PLATFORM_TYPES_H_ */