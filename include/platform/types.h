typedef __u_short           u_short;

typedef __s_int             s_int;
typedef __u_int             u_int;

typedef __s_long            s_long;
typedef __u_long            u_long;

typedef __s_llong           s_llong;
typedef __u_llong           u_llong;

#endif /* _PLATFORM_TYPES_H_ */